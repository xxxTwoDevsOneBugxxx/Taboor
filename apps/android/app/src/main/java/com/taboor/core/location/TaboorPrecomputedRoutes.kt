    fun findBranchIdForCoordinate(lat: Double, lng: Double): String? {
        var closestId: String? = null
        var minDiff = 0.05
        for ((id, coord) in branchCoordinatesById) {
            val diff = abs(coord.latitude - lat) + abs(coord.longitude - lng)
            if (diff < minDiff) {
                minDiff = diff
                closestId = id
            }
        }
        return closestId
    }

    fun findMatchingBranchId(lat: Double, lng: Double): String? = findBranchIdForCoordinate(lat, lng)

    fun getRoute(branchId: String?): List<LatLng>? = getRouteForBranchId(branchId)

    fun getRouteForBranchId(branchId: String?): List<LatLng>? {
        if (branchId == null) return null
