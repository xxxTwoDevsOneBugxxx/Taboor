    }

    fun getRouteForCoordinate(lat: Double, lng: Double): List<LatLng> {
        val branchId = findBranchIdForCoordinate(lat, lng)
        if (branchId != null) {
            routesById[branchId]?.let { return it }
        }
        return listOf(
            LatLng(30.0380153, 31.2130705),
            LatLng(lat, lng)
        )
    }

    fun getEstimatedMinutes(branchId: String? = null, lat: Double = 30.0585, lng: Double = 31.3466): Int {
        if (branchId != null && minutesById.containsKey(branchId)) {
            return minutesById[branchId] ?: 15
        }
        val matchedId = findBranchIdForCoordinate(lat, lng)
        return if (matchedId != null) minutesById[matchedId] ?: 15 else 15
    }

    fun getDistanceKm(branchId: String? = null, lat: Double = 30.0585, lng: Double = 31.3466): String {
        if (branchId != null && distKmById.containsKey(branchId)) {
