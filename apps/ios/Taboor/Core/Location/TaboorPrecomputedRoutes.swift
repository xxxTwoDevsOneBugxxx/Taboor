    public static func boundingMapRect(for branch: ServiceBranch) -> MKMapRect {
        let coords = route(for: branch)
        let dest = CLLocationCoordinate2D(latitude: branch.lat, longitude: branch.lng)
        let start = CLLocationCoordinate2D(latitude: 30.0380153, longitude: 31.2130705)

        var rect = MKMapRect.null
        // Always include start, destination, and all points
        rect = rect.union(MKMapRect(origin: MKMapPoint(start), size: MKMapSize(width: 0.1, height: 0.1)))
        rect = rect.union(MKMapRect(origin: MKMapPoint(dest), size: MKMapSize(width: 0.1, height: 0.1)))
        for coord in coords {
            rect = rect.union(MKMapRect(origin: MKMapPoint(coord), size: MKMapSize(width: 0.1, height: 0.1)))
        }

        // Generous breathing margins so pins, labels, and bottom/top glass cards never occlude the route
        let dxPadding = max(rect.size.width * 0.40, 2200)
        let dyPadding = max(rect.size.height * 0.70, 3200)
        return rect.insetBy(dx: -dxPadding, dy: -dyPadding)
    }

